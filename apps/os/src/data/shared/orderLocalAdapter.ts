/**
 * Phase 8 local adapter. It maps the current operational Order store to the
 * canonical shared order contract without requiring a live Supabase project.
 */
import type { OrderLineItem, OrderTableRow } from '../../types/orders'
import type { ResolvedStorefrontOrderPricing } from './orderDomain'
import type { SharedOrder } from './contracts'
import type { Json } from './databaseTypes'

export const resolvedPricingToOrderLineItems = (
  resolved: ResolvedStorefrontOrderPricing,
  idFactory: () => string,
): OrderLineItem[] => resolved.items.map((item) => ({
  id: idFactory(),
  productId: item.productId,
  variantId: item.variantId,
  productName: item.productNameSnapshot,
  productCodeSnapshot: item.productCodeSnapshot,
  productNameSnapshot: item.productNameSnapshot,
  variantSkuSnapshot: item.variantSkuSnapshot,
  variantSizeSnapshot: item.variantSizeSnapshot,
  quantity: item.quantity,
  unitPriceIdr: item.unitPriceIdr,
}))

const firstCreatedAt = (order: OrderTableRow): string =>
  order.createdAt ?? order.updatedAt ?? '1970-01-01T00:00:00.000Z'

export const orderTableRowToSharedOrder = (order: OrderTableRow): SharedOrder => {
  const orderId = order.id ?? `legacy-order-${order.orderNumber.toLowerCase()}`
  return {
    id: orderId,
    orderNumber: order.orderNumber,
    revision: order.revision ?? 1,
    storefrontIdempotencyKey: order.storefrontIdempotencyKey,
    customerId: order.customerId,
    customerNameSnapshot: order.customerSnapshot?.name ?? order.customerName,
    customerWhatsappSnapshot: order.customerSnapshot?.whatsappNumber ?? order.customerSnapshot?.phone,
    customerEmailSnapshot: order.customerSnapshot?.email,
    customerProfileSuggestions: order.customerProfileSuggestions,
    source: order.source,
    fulfillment: order.fulfillment,
    status: order.status,
    branchId: order.branch,
    totalIdr: order.totalIdr,
    itemsSubtotalIdr: order.itemsSubtotalIdr ?? order.items?.reduce((sum, item) => sum + item.unitPriceIdr * item.quantity, 0) ?? order.totalIdr,
    discountIdr: order.discountIdr ?? 0,
    deliveryFeeIdr: order.deliveryFeeIdr ?? 0,
    paymentStatus: order.paymentStatus,
    paymentMethod: order.paymentMethod,
    paidAmountIdr: order.paidAmountIdr ?? 0,
    paymentHistory: order.paymentHistory?.map((event) => ({ ...event })),
    refundAmountIdr: order.refundAmountIdr,
    refundReason: order.refundReason,
    refundInitiatedBy: order.refundInitiatedBy,
    refundInitiatedAt: order.refundInitiatedAt,
    refundCompletedBy: order.refundCompletedBy,
    refundCompletedAt: order.refundCompletedAt,
    refundCancelledBy: order.refundCancelledBy,
    refundCancelledAt: order.refundCancelledAt,
    refundCancellationReason: order.refundCancellationReason,
    scheduleLabel: order.scheduleLabel,
    scheduleDate: order.scheduleDate,
    scheduleTime: order.scheduleTime,
    requestedPickupDate: order.requestedPickupDate,
    requestedPickupTime: order.requestedPickupTime,
    actualPickedUpAt: order.actualPickedUpAt,
    orderNote: order.orderNote ?? order.internalNote,
    greetingMessage: order.greetingMessage ?? order.giftMessage,
    greetingCardName: order.greetingCardName,
    deliveryAddress: order.deliveryAddress,
    deliveryInstructions: order.deliveryInstructions,
    promoCode: order.promoCode,
    floristDisplayName: order.florist,
    floristAssignedEmployeeId: order.floristAssignedEmployeeId,
    floristAssignedAt: order.floristAssignedAt,
    floristAssignedForDate: order.floristAssignedForDate,
    floristAssignedForTime: order.floristAssignedForTime,
    floristAssignedByEmployeeId: order.floristAssignedByEmployeeId,
    floristAssignedByName: order.floristAssignedByName,
    floristScheduleOverride: order.floristScheduleOverride,
    floristScheduleOverrideReason: order.floristScheduleOverrideReason,
    floristScheduledBranchId: order.floristScheduledBranchId,
    floristAssignedBranchId: order.floristAssignedBranchId,
    floristScheduledShiftStart: order.floristScheduledShiftStart,
    floristScheduledShiftEnd: order.floristScheduledShiftEnd,
    processingStartedAt: order.processingStartedAt,
    adminHandledEmployeeId: order.adminHandledEmployeeId,
    adminHandledByName: order.adminHandledByName,
    completedAt: order.completedAt,
    financeVerified: order.financeVerified,
    financeVerifiedBy: order.financeVerifiedBy,
    financeVerifiedAt: order.financeVerifiedAt,
    financeVerificationStatus: order.financeVerificationStatus,
    financeVerificationNote: order.financeVerificationNote,
    financeVerificationActor: order.financeVerificationActor,
    financeVerificationAt: order.financeVerificationAt,
    financeResubmittedBy: order.financeResubmittedBy,
    financeResubmittedAt: order.financeResubmittedAt,
    financeResubmissionNote: order.financeResubmissionNote,
    financeSubmissionRevision: order.financeSubmissionRevision,
    pendingChangeRequest: order.pendingChangeRequest as unknown as Json | undefined,
    editUnlocked: order.editUnlocked,
    createdAt: firstCreatedAt(order),
    updatedAt: order.updatedAt ?? firstCreatedAt(order),
    items: (order.items ?? []).map((item) => ({
      id: item.id,
      orderId,
      productId: item.productId,
      variantId: item.variantId,
      productCodeSnapshot: item.productCodeSnapshot,
      productNameSnapshot: item.productNameSnapshot ?? item.productName ?? 'Custom order',
      variantSkuSnapshot: item.variantSkuSnapshot,
      variantSizeSnapshot: item.variantSizeSnapshot,
      quantity: item.quantity,
      unitPriceIdr: item.unitPriceIdr,
    })),
  }
}

